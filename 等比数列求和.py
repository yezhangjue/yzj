# 任务(2)：输入等比数列的首项、公比（不等于 1 且小于 36 的正整数）和一个自然数 n，
# 输出这个数列前 n 项的和。关键步骤要求使用内置函数 int()。


def main():
    # 使用内置函数 int() 将输入的字符串转换为整数
    a = int(input("请输入首项 a："))
    r = int(input("请输入公比 r（不等于 1 且小于 36 的正整数）："))
    n = int(input("请输入自然数 n："))

    if r <= 0 or r == 1 or r >= 36:
        print("公比不符合要求（应为不等于 1 且小于 36 的正整数）！")
        return

    # 等比数列前 n 项和：S = a * (r^n - 1) / (r - 1)
    total = int(a * (r ** n - 1) / (r - 1))
    print(f"该数列前 {n} 项的和为：{total}")


if __name__ == "__main__":
    main()
